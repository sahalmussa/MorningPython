# typecasting.py

# String to integer
age = "23"

age = int(age)

print(age)
print(type(age))

# String to float
price = "25.50"

price = float(price)

print(price)
print(type(price))

# Integer to string
number = 100

number = str(number)

print(number)
print(type(number))

# Integer to float
number = 10

number = float(number)

print(number)
print(type(number))

# Float to integer
price = 25.99

price = int(price)

print(price)