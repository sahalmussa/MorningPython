# datatypes.py

# 1. String
name = "Sahal"

# 2. Integer
age = 23

# 3. Float
height = 1.75

# 4. Boolean
is_student = True

# 5. List
skills = ["Python", "Cybersecurity", "Networking"]

# 6. Tuple
coordinates = (1, 2)

# 7. Set
languages = {"Python", "JavaScript", "Python"}

# 8. Dictionary
person = {
    "name": "Sahal",
    "age": 23,
    "course": "Cybersecurity"
}

# Print values
print(name)
print(age)
print(height)
print(is_student)
print(skills)
print(coordinates)
print(languages)
print(person)
